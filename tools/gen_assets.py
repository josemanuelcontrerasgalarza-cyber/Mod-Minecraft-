def draw_template(path, art, accent=None, bg=None):
    """Dibuja una plantilla ASCII de 16x16 en un PNG."""
    w = h = 16
    base = bg if bg else (0, 0, 0, 0)
    px = [base] * (w * h)
    rows = art.strip('\n').split('\n')
    for y in range(min(h, len(rows))):
        row = rows[y]
        for x in range(min(w, len(row))):
            ch = row[x]
            if ch == 'A':
                col = accent if accent else PALETTE['M']
            else:
                col = PALETTE.get(ch)
            if col:
                px[y * w + x] = col
    write_png(path, px, w, h)

def _noise(seed, x, y, amp):
    b = hashlib.md5(f"{seed}:{x}:{y}".encode()).digest()[0]
    return int((b / 255.0 - 0.5) * amp)

def make_stone_ore(path, base, ore_light, ore_dark):
    """Bloque de piedra con vetas de mineral."""
    w = h = 16
    px = []
    for y in range(h):
        for x in range(w):
            n = _noise("stone", x, y, 36)
            px.append((clamp(base[0] + n), clamp(base[1] + n), clamp(base[2] + n), 255))
    for (bx, by) in [(4, 4), (11, 6), (6, 11), (12, 12), (3, 10)]:
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                if abs(dx) + abs(dy) > 2:
                    continue
                x, y = bx + dx, by + dy
                if 0 <= x < w and 0 <= y < h:
                    px[y * w + x] = ore_dark if (dx == 1 or dy == 1) else ore_light
    write_png(path, px, w, h)

def make_metal_block(path, base):
    """Placa metalica con bisel y remaches."""
    w = h = 16
    light = shade(base, 1.18)
    dark = shade(base, 0.62)
    px = []
    for y in range(h):
        for x in range(w):
            n = _noise("metal", x, y, 10)
            px.append((clamp(base[0] + n), clamp(base[1] + n), clamp(base[2] + n), 255))
    for i in range(w):
        px[i] = light            # borde superior
        px[i * w] = light        # borde izquierdo
        px[(h - 1) * w + i] = dark
        px[i * w + (w - 1)] = dark
    for (rx, ry) in [(2, 2), (13, 2), (2, 13), (13, 13)]:
        px[ry * w + rx] = dark
    write_png(path, px, w, h)

